// Regenerates the model catalog bundled with the Claude Code plugin
// from the app's single source of truth (packages/studio/src/models.js).
// Usage: node scripts/build-plugin-catalog.mjs
import { writeFileSync } from 'node:fs';
import * as m from '../packages/studio/src/models.js';

const groups = [
  ['Text to image', m.t2iModels],
  ['Image to image / edit', m.i2iModels],
  ['Text to video', m.t2vModels],
  ['Image to video', m.i2vModels],
  ['Video to video', m.v2vModels],
  ['Lip sync', m.lipsyncModels],
  ['Motion control', m.motionControlModels],
  ['Audio', m.audioModels],
];

const fmt = (k, v) => {
  let s = `\`${k}\``;
  if (v?.enum) s += ` (${v.enum.slice(0, 12).join(' / ')}${v.enum.length > 12 ? ' / …' : ''})`;
  else if (v?.type) s += ` (${v.type})`;
  if (v?.default !== undefined && v?.default !== null && v?.default !== '') s += ` default ${JSON.stringify(v.default)}`;
  return s;
};

let out = `# MuAPI model catalog\n\nGenerated by \`scripts/build-plugin-catalog.mjs\` from \`packages/studio/src/models.js\`. Do not edit by hand.\n\nEach model is called with \`POST https://api.muapi.ai/api/v1/<endpoint>\`. Fields listed are the JSON body inputs.\n`;
for (const [title, list] of groups) {
  if (!Array.isArray(list)) continue;
  out += `\n## ${title} (${list.length})\n\n`;
  for (const x of list) {
    const inputs = Object.entries(x.inputs || {}).map(([k, v]) => fmt(k, v)).join(', ');
    out += `- **${x.name || x.id}**: endpoint \`${x.endpoint || x.id}\`${inputs ? `. Inputs: ${inputs}` : ''}\n`;
  }
}
const dest = new URL('../plugins/open-generative-ai/skills/generate-media/references/models.md', import.meta.url);
writeFileSync(dest, out);
console.log('wrote', dest.pathname, out.length, 'bytes');
